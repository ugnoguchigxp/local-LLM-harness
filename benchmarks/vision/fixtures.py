"""Build a small, annotated exploratory corpus outside Git."""
import argparse
import hashlib
import json
import shutil
from pathlib import Path
import urllib.request


def main():
    from PIL import Image, ImageDraw, ImageFont
    from matplotlib import mathtext
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--font', type=Path, required=True)
    parser.add_argument('--bus', type=Path, required=True)
    args = parser.parse_args()
    if args.output.resolve().is_relative_to(Path(__file__).resolve().parents[2]):
        raise ValueError('generated images must stay outside the source repository')
    if (args.output / 'manifest.json').exists():
        raise ValueError('corpus already exists; use a new output directory')
    args.output.mkdir(parents=True, exist_ok=True)
    records = []

    def save(name, image, expected, origin='synthetic, generated by fixtures.py'):
        path = args.output / (name + '.png')
        image.convert('RGB').save(path)
        records.append({'id': name, 'path': str(path), 'source': origin,
                        'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                        'size': list(image.size), 'expected': expected})

    font = ImageFont.truetype(str(args.font), 32)
    small = ImageFont.truetype(str(args.font), 26)
    plain = Image.new('RGB', (1000, 200), 'white')
    draw = ImageDraw.Draw(plain)
    jp_lines = ['日本語の文字起こしテスト', '認識番号 12345']
    for y, line in zip([30, 100], jp_lines):
        draw.text((30, y), line, font=font, fill='black')
    save('japanese-text', plain, {'text_lines': jp_lines, 'has_text': True, 'has_table': False})
    save('blank', Image.new('RGB', (640, 480), 'white'),
         {'text_lines': [], 'has_text': False, 'has_table': False, 'has_formula': False,
          'has_person': False})

    for name, labels in [('table-en', [['Item', 'Qty', 'Price'], ['Apple', '12', '100'], ['Pear', '5', '80']]),
                         ('table-ja', [['商品', '数量', '金額'], ['りんご', '12', '100'], ['みかん', '5', '80']])]:
        image = Image.new('RGB', (760, 380), 'white')
        d = ImageDraw.Draw(image)
        xs, ys = [20, 330, 490, 740], [20, 130, 240, 350]
        for x in xs:
            d.line((x, ys[0], x, ys[-1]), fill='black', width=2)
        for y in ys:
            d.line((xs[0], y, xs[-1], y), fill='black', width=2)
        cells = []
        for row, values in enumerate(labels):
            for col, text in enumerate(values):
                x, y = xs[col] + 18, ys[row] + 30
                d.text((x, y), text, font=small, fill='black')
                cells.append({'row': row, 'column': col, 'text': text,
                              'bbox': [xs[col], ys[row], xs[col+1], ys[row+1]],
                              'text_bbox': list(d.textbbox((x, y), text, font=small))})
        save(name, image, {'has_text': True, 'has_table': True, 'rows': 3, 'columns': 3,
                           'table_bbox': [20, 20, 740, 350], 'cells': cells, 'merged': []})

    merged = Image.new('RGB', (760, 480), 'white')
    d = ImageDraw.Draw(merged)
    for y in [20, 130, 240, 350, 460]:
        d.line((20, y, 740, y), fill='black', width=2)
    for x in [20, 490, 740]:
        d.line((x, 20, x, 460), fill='black', width=2)
    d.line((330, 130, 330, 460), fill='black', width=2)
    for x, y, text in [(40, 50, 'Inventory'), (510, 50, '2026'), (40, 160, 'Item'),
                       (350, 160, 'Qty'), (510, 160, 'Price'), (40, 270, 'Apple'),
                       (350, 270, '12'), (510, 270, '100'), (40, 380, 'Pear'),
                       (350, 380, '5'), (510, 380, '80')]:
        d.text((x, y), text, font=small, fill='black')
    save('table-merged', merged, {'has_table': True, 'rows': 4, 'columns': 3,
                                 'table_bbox': [20, 20, 740, 460],
                                 'merged': [{'rows': [0], 'columns': [0, 1]}]})

    for name, expression in [('formula-pythagoras', r'x^2+y^2=z^2'),
                             ('formula-quadratic', r'x=\frac{-b\pm\sqrt{b^2-4ac}}{2a}')]:
        intermediate = args.output / (name + '-render.png')
        mathtext.math_to_image('$' + expression + '$', str(intermediate), dpi=180, format='png')
        with Image.open(intermediate) as source:
            image = Image.new('RGB', (max(640, source.width + 80), max(180, source.height + 60)), 'white')
            rgb = Image.new('RGB', source.size, 'white')
            if source.mode == 'RGBA':
                rgb.paste(source, mask=source.getchannel('A'))
            else:
                rgb.paste(source)
            image.paste(rgb, (40, 30))
        save(name, image, {'has_formula': True, 'latex': expression})
        intermediate.unlink()

    doc = Image.new('RGB', (900, 1000), 'white')
    d = ImageDraw.Draw(doc)
    d.text((50, 35), 'Inventory Report', font=font, fill='black')
    d.text((50, 100), 'Items available in the store.', font=small, fill='black')
    with Image.open(args.output / 'table-en.png') as table:
        doc.paste(table, (50, 170))
    d.text((50, 600), 'Formula', font=small, fill='black')
    with Image.open(args.output / 'formula-pythagoras.png') as formula:
        doc.paste(formula, (50, 650))
    save('document-mixed-en', doc, {'has_table': True, 'has_formula': True,
                                   'reading_order': ['Inventory Report', 'Items available', 'Item', 'Formula']})
    doc_ja = doc.copy()
    d = ImageDraw.Draw(doc_ja)
    d.rectangle((0, 0, 899, 169), fill='white')
    d.text((50, 35), '在庫管理報告書', font=font, fill='black')
    d.text((50, 100), '本日の商品と数量を確認します。', font=small, fill='black')
    with Image.open(args.output / 'table-ja.png') as table:
        doc_ja.paste(table, (50, 170))
    save('document-mixed-ja', doc_ja, {'has_table': True, 'has_formula': True,
                                      'text_contains': ['在庫管理報告書', '商品', 'りんご']})
    with Image.open(args.bus) as image:
        save('bus', image, {'caption_keywords': ['bus'], 'has_person': True,
                             'objects': ['bus', 'person'], 'has_table': False},
             'existing object-recognition acceptance fixture: ' + str(args.bus))
    with urllib.request.urlopen('https://huggingface.co/api/datasets/huggingface/documentation-images', timeout=60) as response:
        revision = json.load(response)['sha']
    url = ('https://huggingface.co/datasets/huggingface/documentation-images/resolve/'
           + revision + '/transformers/tasks/car.jpg')
    car = args.output / 'car-source.jpg'
    with urllib.request.urlopen(url, timeout=60) as response, car.open('wb') as stream:
        shutil.copyfileobj(response, stream)
    with Image.open(car) as image:
        save('car', image, {'caption_keywords': ['car'], 'has_person': False, 'has_table': False}, url)
    (args.output / 'manifest.json').write_text(json.dumps({
        'purpose': 'exploratory fixtures; no representative production accuracy claim',
        'font': {'path': str(args.font), 'sha256': hashlib.sha256(args.font.read_bytes()).hexdigest()},
        'fixtures': records}, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({'fixtures': len(records), 'manifest': str(args.output / 'manifest.json')}))


if __name__ == '__main__':
    main()
